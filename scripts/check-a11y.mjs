// Runs axe-core on every page in dist/ and fails on WCAG 2.2 A/AA violations. jsdom has no
// layout, so rules that need rendering (colour contrast, target size) are left out; the
// colour pairs are checked by hand in DESIGN.md. Run after `npm run build`:
// npm run check:a11y
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createRequire } from 'node:module';
import { JSDOM, VirtualConsole } from 'jsdom';

const require = createRequire(import.meta.url);
const axeSource = readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8');
const distDir = decodeURIComponent(new URL('../dist/', import.meta.url).pathname).replace(
	/^\/([A-Za-z]:)/,
	'$1',
);

function htmlFiles(dir) {
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) return htmlFiles(path);
		return name.endsWith('.html') ? [path] : [];
	});
}

let failures = 0;
let checked = 0;
const pages = htmlFiles(distDir);
for (const file of pages) {
	const page = relative(distDir, file);
	const html = readFileSync(file, 'utf8');
	// Redirect stubs generated by Astro (e.g. the old plugin URL) are not content.
	if (/<meta http-equiv="refresh"/i.test(html)) continue;
	// Pages are checked as delivered, without running their scripts or loading CSS.
	const dom = new JSDOM(html, {
		runScripts: 'outside-only',
		virtualConsole: new VirtualConsole(),
	});
	checked++;
	dom.window.eval(axeSource);
	const result = await dom.window.axe.run(dom.window.document, {
		runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'] },
		rules: { 'color-contrast': { enabled: false }, 'target-size': { enabled: false } },
	});
	for (const violation of result.violations) {
		failures++;
		console.error(`${page}: ${violation.id} (${violation.impact}) ${violation.help}`);
		for (const node of violation.nodes.slice(0, 3)) console.error(`    ${node.target.join(' ')}`);
	}
	dom.window.close();
}

if (failures) {
	console.error(`\n${failures} accessibility violations.`);
	process.exit(1);
}
console.log(`Accessibility OK: ${checked} pages checked with axe-core.`);
